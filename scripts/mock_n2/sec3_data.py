def _rebalance_spoken_options(q_list, seed_offset):
    for idx, q in enumerate(q_list):
        if q["subsectionId"] != "s3_m4":
            continue
        target_idx = (idx + seed_offset) % 3
        cur_idx = q["correctIndex"]
        if cur_idx == target_idx:
            continue
        opts = list(q["options"])
        opts[cur_idx], opts[target_idx] = opts[target_idx], opts[cur_idx]
        q["options"] = opts
        q["correctIndex"] = target_idx

        s_lines = q["script"].split("\n")
        opt_lines = [_re.sub(r"^[１２３]\u3000", "", L) for L in s_lines[-3:]]
        opt_lines[cur_idx], opt_lines[target_idx] = opt_lines[target_idx], opt_lines[cur_idx]
        zen_nums = ["１", "２", "３"]
        s_lines[-3:] = [f"{zen_nums[i]}\u3000{opt_lines[i]}" for i in range(3)]
        q["script"] = "\n".join(s_lines)

        t_list = list(q["tracks"])
        t_opts = []
        for t_text, t_voice, t_pause in t_list[-3:]:
            body = _re.sub(r"^[１２３]。", "", t_text)
            t_opts.append((body, t_voice, t_pause))
        t_opts[cur_idx], t_opts[target_idx] = t_opts[target_idx], t_opts[cur_idx]
        for i in range(3):
            body, v, p = t_opts[i]
            t_list[-3 + i] = (f"{zen_nums[i]}。{body}", v, p)
        q["tracks"] = t_list


_rebalance_spoken_options(SET1_QUESTIONS, 0)
_rebalance_spoken_options(SET2_QUESTIONS, 1)


def synthesize_multi_speaker_question(client, q_item, force=False):
    rel_path = q_item["audioUrl"]
    out_main = os.path.join(BASE_DIR, rel_path)
    out_pub = os.path.join(BASE_DIR, "public", rel_path)
    os.makedirs(os.path.dirname(out_main), exist_ok=True)
    os.makedirs(os.path.dirname(out_pub), exist_ok=True)

    if not force and os.path.exists(out_main) and os.path.getsize(out_main) > 1000:
        return False

    combined_mp3 = b""
    audio_config = texttospeech.AudioConfig(
        audio_encoding=texttospeech.AudioEncoding.MP3,
        speaking_rate=0.98
    )

    for text_line, voice_name, pause_ms in q_item["tracks"]:
        ssml = f"<speak>{text_line}<break time=\"{pause_ms}ms\"/></speak>"
        synthesis_input = texttospeech.SynthesisInput(ssml=ssml)
        voice = texttospeech.VoiceSelectionParams(
            language_code="ja-JP",
            name=voice_name
        )
        response = client.synthesize_speech(
            input=synthesis_input,
            voice=voice,
            audio_config=audio_config
        )
        combined_mp3 += response.audio_content

    with open(out_main, "wb") as f:
        f.write(combined_mp3)
    with open(out_pub, "wb") as f:
        f.write(combined_mp3)
    return True


