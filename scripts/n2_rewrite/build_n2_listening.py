def tts_clean(text):
    t = _EXPL.sub(lambda m: m.group(2), text)
    t = re.sub(r'<rt>.*?</rt>', '', t)
    t = re.sub(r'<[^>]+>', '', t)
    t = t.replace('「', '').replace('」', '')
    for a, b in N2_TTS_FIXES:
        t = t.replace(a, b)
    return t.strip()

def build_segments(it):
    V = {'n': 'ja-JP-Neural2-B', 'f': 'ja-JP-Neural2-B', 'm': 'ja-JP-Neural2-C'}
    n = it['q_num']
    sec = it['section']
    head = f"だい{num_reading(n)}もん。"
    segs = []
    if sec in ("問題1 課題理解", "問題2 ポイント理解"):
        segs.append((V['n'], head + tts_clean(it['intro']), 1000))
        for who, line in it['dialogue']:
            segs.append((V[who], tts_clean(line), 800))
        segs.append((V['n'], "質問。" + tts_clean(it['prompt']), 1800))
    elif sec == "問題3 概要理解":
        segs.append((V['n'], head + tts_clean(it['intro']), 1000))
        segs.append((V[it['speaker']], tts_clean(it['monologue']), 1000))
        segs.append((V['n'], "質問。" + tts_clean(it['prompt']), 1800))
    elif sec == "問題4 即時応答":
        segs.append((V['n'], head + "短い文を聞いて、最もよい返答を選んでください。", 900))
        segs.append((V[it['asker']], tts_clean(it['prompt']), 1200))
        for i, c in enumerate(it['choices']):
            num_w = ['いち', 'に', 'さん'][i]
            segs.append((V[it['replier']], f"{num_w}ばん、{tts_clean(c)}", 1500))
    elif sec == "問題5 統合理解":
        segs.append((V['n'], head + tts_clean(it['intro']), 1000))
        for who, line in it['dialogue']:
            segs.append((V[who], tts_clean(line), 800))
        segs.append((V['n'], "質問。" + tts_clean(it['prompt']), 1800))
    return segs

def build():
    out = []
    errs = []
    for it in ITEMS:
        n = it['q_num']
        sec = it['section']
        prompt_plain = P(it['prompt'])
        prompt_ruby = R_n2(it['prompt'])
        choices_ruby = [R_n2(c) for c in it['choices']]
        ex_ja = R_n2(it['exp']['ja'])

        # Build script_html and speech_dialogue
        dlg_lines_plain = []
        dlg_html = f'<p class="text-xs font-bold text-slate-400 mb-1">{R_n2(f"第{n}問。")}{R_n2(it.get("intro", ""))}</p>'
        if sec in ("問題1 課題理解", "問題2 ポイント理解", "問題5 統合理解"):
            for who, line in it['dialogue']:
                lab = '女の人' if who == 'f' else '男の人'
                dlg_lines_plain.append(f"{lab}：{P(line)}")
                dlg_html += f'<p><span class="font-bold text-[#1995AD]">{R_n2(lab)}：</span>{R_n2(line)}</p>'
            dlg_html += f'<p class="text-xs font-bold text-[#B8596E] mt-2">{R_n2("質問")}：{prompt_ruby}</p>'
        elif sec == "問題3 概要理解":
            lab = '女の人' if it['speaker'] == 'f' else '男の人'
            dlg_lines_plain.append(P(it['monologue']))
            dlg_html += f'<p><span class="font-bold text-[#1995AD]">{R_n2(lab)}：</span>{R_n2(it["monologue"])}</p>'
            dlg_html += f'<p class="text-xs font-bold text-[#B8596E] mt-2">{R_n2("質問")}：{prompt_ruby}</p>'
        elif sec == "問題4 即時応答":
            asker_lab = '女の人' if it['asker'] == 'f' else '男の人'
            dlg_lines_plain.append(f"{asker_lab}：{prompt_plain}")
            dlg_html = f'<p class="text-xs font-bold text-slate-400 mb-1">{R_n2(f"第{n}問。")}</p>'
            dlg_html += f'<p><span class="font-bold text-[#1995AD]">{R_n2(asker_lab)}：</span>{prompt_ruby}</p>'
            for i, c_r in enumerate(choices_ruby):
                dlg_lines_plain.append(f"{i+1}番：{P(it['choices'][i])}")
                dlg_html += f'<p><span class="font-bold text-[#1995AD]">{i+1}{R_n2("番")}：</span>{c_r}</p>'
            dlg_html += f'<p class="text-xs font-bold text-[#B8596E] mt-2">{R_n2("質問：発話を聞いて、最も適した返答を選んでください。")}</p>'

        script_html = f'<div class="space-y-2 text-sm leading-relaxed">{dlg_html}</div>'
        segs = build_segments(it)
        speech_audio_text = '\n\n'.join(t for _, t, _ in segs)

        # Lint ruby leaks
        for field_name, html_val in (('prompt_ruby', prompt_ruby), ('choices', ''.join(choices_ruby)), ('exp_ja', ex_ja), ('script_html', script_html)):
            leaks = lint_ruby(html_val)
            if leaks:
                errs.append(f"Q{n} {field_name} ruby leak: {''.join(leaks)}")

        # Sensitive & brand check
        all_txt = prompt_plain + ''.join(P(c) for c in it['choices']) + ' '.join(dlg_lines_plain) + P(ex_ja)
        sh = sensitive_hits(all_txt)
        if sh:
            errs.append(f"Q{n} sensitive hits: {sh}")
        for bad in ('Zoom', 'LINE', 'SNS', 'Google', 'Amazon'):
            if bad in all_txt:
                errs.append(f"Q{n} banned word '{bad}' found in text")
        if re.search(r'(?:^|[。！？\s「（：])あ、', all_txt):
            errs.append(f"Q{n} interjection 'あ、' found in text")

        img_rel = it['img_url']
        has_img = os.path.exists(os.path.join(REPO, img_rel))

        out.append({
            'id': f'lis_q{n}',
            'section': sec,
            'q_num': n,
            'title': it['title'],
            'has_illustration': True,
            'illustration_url': img_rel,
            'prompt': prompt_plain,
            'prompt_ruby': prompt_ruby,
            'speech_dialogue': '\n'.join(dlg_lines_plain),
            'speech_audio_text': speech_audio_text,
            'choices': choices_ruby,
            'choices_ruby': choices_ruby,
            'answer': it['answer'],
            'script_html': script_html,
            'explanation': {
                'ja': ex_ja,
                'en': it['exp']['en'],
                'zh': it['exp']['zh'],
                'ko': it['exp']['ko'],
            },
            'audio_file': f'audio/listening/n2_q{n}.mp3',
            '_segments': segs,
            '_has_img_disk': has_img,
        })

    if errs:
        print(f"Found {len(errs)} errors:")
        for e in errs:
            print(" -", e)
        sys.exit(1)
    return out

if __name__ == '__main__':
    out = build()
    print(f"Validated {len(out)} N2 listening questions with 0 errors.")
    pub = [{k: v for k, v in q.items() if not k.startswith('_')} for q in out]
    if '--check' not in sys.argv:
        data_obj = {
            'test_id': 'jlpt_n2_listening_test_01',
            'title': 'JLPT N2 聴解実戦模試 第1回',
            'level': 'N2',
            'total_questions': len(pub),
            'questions': pub,
        }
        for rel_p in ('database/jlpt_n2_listening_data.js', 'public/database/jlpt_n2_listening_data.js'):
            full_p = os.path.join(REPO, rel_p)
            write_js(full_p, ['JLPT N2 Listening Comprehension Data (31 Questions, Multi-Speaker Audio & 4:3 Illustrations)'], [('JLPT_N2_LISTENING_DATA', data_obj)])
        print("Wrote database/jlpt_n2_listening_data.js and public/database/jlpt_n2_listening_data.js")

    if '--audio' in sys.argv:
        os.environ.setdefault('GOOGLE_APPLICATION_CREDENTIALS', os.path.join(REPO, 'secrets/google_tts_key.json'))
        from google.cloud import texttospeech
        cl = texttospeech.TextToSpeechClient()
        mf_path = os.path.join(HERE, 'n2_listening_audio_manifest.json')
        mf = json.load(open(mf_path)) if os.path.exists(mf_path) else {}
        only = set(int(x) for x in sys.argv[sys.argv.index('--only') + 1:]) if '--only' in sys.argv else set()

        def synth(text, voice, ssml=False):
            inp = texttospeech.SynthesisInput(ssml=text) if ssml else texttospeech.SynthesisInput(text=text)
            r = cl.synthesize_speech(
                input=inp,
                voice=texttospeech.VoiceSelectionParams(language_code='ja-JP', name=voice),
                audio_config=texttospeech.AudioConfig(audio_encoding=texttospeech.AudioEncoding.MP3, speaking_rate=0.96)
            )
            return r.audio_content

        chars = 0
        for q in out:
            n = q['q_num']
            segs = q['_segments']
            h = hashlib.sha1(json.dumps(segs, ensure_ascii=False).encode()).hexdigest()
            dst = [
                os.path.join(REPO, 'audio/listening', f'n2_q{n}.mp3'),
                os.path.join(REPO, 'public/audio/listening', f'n2_q{n}.mp3'),
            ]
            if mf.get(str(n)) == h and os.path.exists(dst[0]) and not (only and n in only):
                continue
            if only and n not in only and mf.get(str(n)) == h:
                continue
            buf = bytearray()
            for voice, text, pause in segs:
                buf += synth(text, voice)
                chars += len(text)
                if pause:
                    buf += synth(f'<speak><break time="{pause}ms"/></speak>', voice, ssml=True)
            for d in dst:
                os.makedirs(os.path.dirname(d), exist_ok=True)
                with open(d, 'wb') as f:
                    f.write(buf)
            mf[str(n)] = h
            with open(mf_path, 'w') as f:
                json.dump(mf, f, indent=1)
            print(f"Synthesized n2_q{n}.mp3 ({len(buf)} bytes)")
        print("Total synthesized characters:", chars)
