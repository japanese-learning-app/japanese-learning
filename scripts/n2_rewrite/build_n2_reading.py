def R_rd(text):
    if not text:
        return ''
    # Split by existing {...|...} or <ruby>...</ruby> or HTML tags so replacements only touch raw text
    parts = re.split(r'(\{[^{}]+\}|<ruby>.*?</ruby>|<[^>]+>)', text)
    for i in range(0, len(parts), 2):
        seg = parts[i]
        for old, new in N2_READING_PRE + N2_PRE_REPLACEMENTS:
            if old in seg:
                # Recurse/protect newly inserted {...} by splitting again
                subparts = re.split(r'(\{[^{}]+\})', seg)
                for j in range(0, len(subparts), 2):
                    subparts[j] = subparts[j].replace(old, new)
                seg = ''.join(subparts)
        parts[i] = seg
    return R(''.join(parts))

