def build_passage_obj(raw_p, p_class):
    body_html = ''.join(f'<p class="{p_class}">{R_rd(par)}</p>' for par in raw_p['body'])
    vocab_list = []
    for w, m in raw_p['vocab']:
        vocab_list.append({
            'word': P(w),
            'meaning': P(m),
            'word_ruby': R_rd(w),
            'meaning_ruby': R_rd(m),
        })
    qs = []
    for q in raw_p['questions']:
        q_html = R_rd(q['question'])
        c_html = [R_rd(c) for c in q['choices']]
        qs.append({
            'q_num': 0, # assigned sequentially later
            'question_html': q_html,
            'evidence_id': q['evidence_id'],
            'choices': c_html,
            'answer': q['answer'],
            'explanation': {
                'ja': R_rd(q['exp']['ja']),
                'en': q['exp']['en'],
                'zh': q['exp']['zh'],
                'ko': q['exp']['ko'],
            },
            'question_html_ruby': q_html,
            'choices_ruby': list(c_html),
        })
    t_plain = P(raw_p['title'])
    t_ruby = R_rd(raw_p['title'])
    return {
        'id': '',
        'type': raw_p['type'],
        'section_name': raw_p['section_name'],
        'genre': raw_p['genre'],
        'title': t_plain,
        'time_est': raw_p['time_est'],
        'text_html': body_html,
        'vocab_notes': vocab_list,
        'questions': qs,
        'title_ruby': t_ruby,
        'text_html_ruby': body_html,
    }

def build_all():
    existing = fix_existing_passages()
    # existing[0..4] are 問題10 短文読解 (p1..p5)
    # existing[5..7] are 問題11 中文読解 (p6..p8)
    # existing[8] is 問題12 統合理解 (p9)
    # existing[9] is 問題13 主張理解 (p10)
    # existing[10] is 問題14 情報検索 (p11)
    short_new = [build_passage_obj(x, 'mb-3') for x in NEW_SHORT_PASSAGES]
    mid_new = [build_passage_obj(x, 'mb-4') for x in NEW_MID_PASSAGES]

    all_passages = (
        existing[0:5] + short_new +
        existing[5:8] + mid_new +
        existing[8:11]
    )

    q_counter = 1
    errs = []
    ans_dist = [0, 0, 0, 0]
    for idx, p in enumerate(all_passages, 1):
        old_id = p['id']
        new_id = f'p{idx}'
        p['id'] = new_id
        for q in p['questions']:
            q['q_num'] = q_counter
            q_counter += 1
            ans_dist[q['answer']] += 1
            for fn, val in (('question_html', q['question_html']), ('choices', ''.join(q['choices'])), ('exp_ja', q['explanation']['ja'])):
                leaks = lint_ruby(val)
                if leaks:
                    errs.append(f"{new_id} Q{q['q_num']} {fn} ruby leak: {''.join(leaks)}")
            if q['choices'] != q['choices_ruby']:
                errs.append(f"{new_id} Q{q['q_num']} choices != choices_ruby")
        for fn, val in (('title_ruby', p['title_ruby']), ('text_html', p['text_html'])):
            leaks = lint_ruby(val)
            if leaks:
                errs.append(f"{new_id} {fn} ruby leak: {''.join(leaks)}")
        for v in p.get('vocab_notes', []):
            for fn in ('word_ruby', 'meaning_ruby'):
                leaks = lint_ruby(v[fn])
                if leaks:
                    errs.append(f"{new_id} vocab {fn} ruby leak: {''.join(leaks)}")
        all_txt = P(p['title']) + P(p['text_html']) + ''.join(P(q['question_html']) + ''.join(P(c) for c in q['choices']) for q in p['questions'])
        sh = sensitive_hits(all_txt)
        if sh:
            errs.append(f"{new_id} sensitive hits: {sh}")
        for bad in ('Zoom', 'LINE', 'SNS', 'Google', 'Amazon', '準拠', '公式'):
            if bad in all_txt:
                errs.append(f"{new_id} banned word '{bad}'")

    if errs:
        print(f"Found {len(errs)} errors:")
        for e in errs:
            print(" -", e)
        sys.exit(1)

    print(f"Validated {len(all_passages)} N2 reading passages ({q_counter - 1} questions) with 0 errors. Answer dist: {ans_dist}")
    return all_passages

