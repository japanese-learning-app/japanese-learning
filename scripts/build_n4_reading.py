def build():
    errs = []
    out_passages = []
    all_answers = []

    for p in PASSAGES:
        pid = p['passage_id']
        title_ruby = RR(p['title'])
        text_html = RR(p['body'], skip_u=False)

        for k, h in (('title', title_ruby), ('body', text_html)):
            leak = lint_ruby(h)
            if leak:
                errs.append(f'{pid}: ruby leak in {k}: {"".join(leak)}')

        sh = sensitive_hits(P(p['title']) + P(p['body']))
        if sh:
            errs.append(f'{pid}: sensitive hits {sh}')

        out_qs = []
        for q in p['questions']:
            qn = q['q_num']
            q_html = RR(q['question'])
            c_html = [RR(c) for c in q['choices']]
            a_num = q['answer'] + 1
            pre = {
                'ja': RR(f'正解は{a_num}番です。'),
                'en': f'The correct answer is Choice {a_num}. ',
                'zh': f'正確答案是選項{a_num}。',
                'ko': f'정답은 {a_num}번입니다. ',
            }
            exja = pre['ja'] + RR(q['exp']['ja'])

            for k, h in (('q', q_html), ('choices', ''.join(c_html)), ('exp', exja)):
                leak = lint_ruby(h)
                if leak:
                    errs.append(f'Q{qn}: ruby leak in {k}: {"".join(leak)}')

            ev_id = q['evidence_id']
            if f'id="{ev_id}"' not in text_html:
                errs.append(f'Q{qn}: evidence_id {ev_id} not found in passage {pid}')

            sh_q = sensitive_hits(P(q['question']) + ''.join(P(c) for c in q['choices']) + q['exp']['ja'])
            if sh_q:
                errs.append(f'Q{qn}: sensitive hits {sh_q}')

            all_answers.append(q['answer'])
            out_qs.append({
                'q_num': qn,
                'question_html': q_html,
                'choices': c_html,
                'answer': q['answer'],
                'evidence_id': ev_id,
                'explanation': {
                    'ja': exja,
                    'en': pre['en'] + q['exp']['en'],
                    'zh': pre['zh'] + q['exp']['zh'],
                    'ko': pre['ko'] + q['exp']['ko'],
                }
            })

        out_passages.append({
            'passage_id': pid,
            'section': p['section'],
            'section_name': p['section_name'],
            'genre': p['genre'],
            'time_est': p['time_est'],
            'title': P(p['title']),
            'title_ruby': title_ruby,
            'text_html': text_html,
            'vocab_notes': p['vocab_notes'],
            'questions': out_qs,
        })

    if errs:
        print('ERRORS FOUND:')
        for e in errs:
            print(' -', e)
        sys.exit(1)

    runs = [i + 1 for i in range(2, len(all_answers)) if all_answers[i] == all_answers[i-1] == all_answers[i-2]]
    print(f'Total passages: {len(out_passages)}, Total Qs: {len(all_answers)}, dist={dict(sorted(collections.Counter(all_answers).items()))}, 3-runs={runs}')
    assert not runs, f'3-in-a-row answer run found at {runs}'

    data = {
        'test_id': 'jlpt_n4_reading_test_01',
        'title': 'JLPT N4 読解 総合実戦模試（全11パッセージ・21問）',
        'level': 'N4',
        'total_passages': len(out_passages),
        'total_questions': len(all_answers),
        'passages': out_passages,
    }

    js_str = '// JLPT N4 Reading Comprehension Data (11 Passages / 21 Questions)\n'
    js_str += 'window.JLPT_N4_READING_DATA = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
    for dst_rel in ('database/jlpt_n4_reading_data.js', 'public/database/jlpt_n4_reading_data.js'):
        p = os.path.join(REPO, dst_rel)
        if os.path.exists(os.path.dirname(p)):
            with open(p, 'w', encoding='utf-8') as f:
                f.write(js_str)
    print('Successfully wrote database/jlpt_n4_reading_data.js')


if __name__ == '__main__':
    build()
